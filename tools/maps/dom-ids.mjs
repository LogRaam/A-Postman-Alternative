// DOM ids: the names src/index.html and the ui modules agree on. A renamed id breaks a button with no error at
// build time, and no other map sees the template, so this one pairs every id the template declares with every
// place that refers to it. Built 26/10/2026 after a review named this contract as unwatched.

import { listFiles, readText, readModule, walk } from '../source.mjs';

export const TEMPLATE = 'src/index.html';

/** Ids the template declares: [{ id, line }], in order, duplicates kept so they can be reported. */
export function declaredIds(root) {
  const html = readText(TEMPLATE, root);
  return [...html.matchAll(/\sid="([^"]+)"/g)].map(m => ({ id: m[1], line: lineAt(html, m.index) }));
}

/**
 * Every reference to an id, each labelled with how it was found:
 * - (byId): a literal passed to byId, imported from ./page.js. A fact: the import is checked.
 * - (selector): "#id" inside a literal passed to querySelector, querySelectorAll or closest.
 * - (template): aria-controls="id" or for="id" in the template.
 * - (css): #id in a selector of the template's <style>.
 * Lookups whose id is computed at run time are returned apart, in computed.
 */
export function idReferences(root) {
  const uses = [];
  const computed = [];
  for (const path of listFiles('src', '.js', root)) {
    const module = readModule(path, root);
    const importsById = module.imports.some(imp => imp.from === 'src/ui/page.js' && imp.names.includes('byId'));
    const definesById = module.declarations.some(d => d.name === 'byId');
    walk(module.ast, node => {
      if (node.type !== 'CallExpression') return;
      const callee = node.callee;
      const first = node.arguments[0];
      const literal = first && first.type === 'Literal' && typeof first.value === 'string' ? first.value : null;
      const line = node.loc.start.line;
      if (callee.type === 'Identifier' && callee.name === 'byId' && (importsById || definesById)) {
        if (literal !== null) uses.push({ id: literal, where: path, line, mode: 'byId' });
        else computed.push({ where: path, line, text: module.text.slice(first.start, first.end) });
      }
      const method = callee.type === 'MemberExpression' && callee.property.name;
      if (method === 'getElementById') {
        if (literal !== null) uses.push({ id: literal, where: path, line, mode: 'getElementById' });
        else computed.push({ where: path, line, text: module.text.slice(first.start, first.end) });
      }
      if (['querySelector', 'querySelectorAll', 'closest'].includes(method) && literal !== null) {
        for (const m of literal.matchAll(/#([\w-]+)/g)) uses.push({ id: m[1], where: path, line, mode: 'selector' });
      }
    });
  }
  const html = readText(TEMPLATE, root);
  for (const m of html.matchAll(/\s(aria-controls|for)="([^"]+)"/g)) uses.push({ id: m[2], where: TEMPLATE, line: lineAt(html, m.index), mode: 'template' });
  const style = html.match(/<style>([\s\S]*?)<\/style>/);
  if (style) {
    const offset = style.index + '<style>'.length;
    for (const block of style[1].matchAll(/([^{}]+)\{/g)) {
      for (const m of block[1].matchAll(/#([a-zA-Z][\w-]*)/g)) uses.push({ id: m[1], where: TEMPLATE, line: lineAt(html, offset + block.index), mode: 'css' });
    }
  }
  return { uses, computed };
}

/** Ids referred to by code but not declared by the template: each one is a lookup that throws, or a dead selector. */
export function missingIds(root) {
  const declared = new Set(declaredIds(root).map(d => d.id));
  return [...new Set(idReferences(root).uses.filter(u => u.mode !== 'css' && !declared.has(u.id)).map(u => u.id))].sort();
}

/** Ids the template declares more than once. */
export function duplicateIds(root) {
  const seen = new Map();
  for (const { id } of declaredIds(root)) seen.set(id, (seen.get(id) || 0) + 1);
  return [...seen].filter(([, n]) => n > 1).map(([id]) => id).sort();
}

export function generateDomIds(root) {
  const declared = declaredIds(root);
  const { uses, computed } = idReferences(root);
  const missing = missingIds(root);
  const duplicates = duplicateIds(root);
  // One line per place: an id looked up twice on the same line is listed once.
  const byIdName = new Map();
  const seen = new Set();
  for (const use of uses) {
    const key = use.id + '|' + use.where + '|' + use.line + '|' + use.mode;
    if (seen.has(key)) continue;
    seen.add(key);
    byIdName.set(use.id, [...(byIdName.get(use.id) || []), use]);
  }

  const lines = [
    '# DOM ids: what the template and the code agree on',
    '',
    'GENERATED by `tools/maps/dom-ids.mjs`. Do not edit. `npm test` fails when this file no longer matches the',
    'code; run `npm run update-maps`, read what moved, and commit the map with the change.',
    '',
    declared.length + ' ids declared in `' + TEMPLATE + '`, ' + uses.length + ' references. Look here BEFORE renaming an id',
    'or adding a lookup. Each reference says how it was found: (byId) a literal passed to `byId`, imported from',
    '`src/ui/page.js` (a fact); (getElementById) a literal passed to it directly; (selector) `#id` inside a literal',
    'CSS selector; (template) `aria-controls` or `for` in the template; (css) a selector in the template\'s style.',
    'Ids built at run time are not checked: they are listed under "Computed lookups".',
    '',
    '## Referred to but not declared',
    '',
    'Ratchet: may not grow (`tools/maps/ratchets.mjs`). A lookup here throws in `byId`, or selects nothing.',
    '',
    ...(missing.length ? missing.map(id => '- `' + id + '`: ' + byIdName.get(id).map(describe).join('; ')) : ['None.']),
    '',
    '## Declared more than once',
    '',
    'Ratchet: may not grow. The browser returns the first, so the second is unreachable by id.',
    '',
    ...(duplicates.length ? duplicates.map(id => '- `' + id + '`') : ['None.']),
    '',
    '## Declared, and referred to by nothing',
    '',
    'Not an error (an id can be a link target or kept for tests), but a candidate for removal.',
    '',
  ];
  const unused = [...new Set(declared.map(d => d.id))].filter(id => !byIdName.has(id)).sort();
  lines.push(...(unused.length ? unused.map(id => '- `' + id + '`') : ['None.']));

  lines.push('', '## Every declared id', '', '| Id | Template line | Referred to by |', '|---|---|---|');
  for (const { id, line } of [...declared].sort((a, b) => a.id.localeCompare(b.id) || a.line - b.line)) {
    const refs = (byIdName.get(id) || []).map(describe);
    lines.push('| `' + id + '` | ' + line + ' | ' + (refs.length ? refs.join('<br>') : '(nothing)') + ' |');
  }

  lines.push('', '## Computed lookups', '', 'The id is an expression, so this map cannot check it. Keep these few.', '');
  lines.push(...(computed.length ? computed.map(c => '- `' + c.where + ':' + c.line + '`: `' + c.text + '`') : ['None.']));
  return lines.join('\n') + '\n';
}

/** "src/ui/editor.js:21 (byId)" */
function describe(use) {
  return '`' + use.where + ':' + use.line + '` (' + use.mode + ')';
}

/** The 1-based line of a character offset. */
function lineAt(text, index) {
  return text.slice(0, index).split('\n').length;
}
