// Inventory: every module under src/, by layer, with every top-level declaration and its one-line doc.
// Answers "does this already exist, and where?" before anything new is written.

import { listFiles, readModule } from '../source.mjs';

/** What each folder is for; a folder not listed here shows as "(no description: add one to inventory.mjs)". */
const LAYERS = {
  'src/core': 'Logic with no DOM and no browser globals. Every module here can be imported by node:test.',
  'src/ui': 'The page: DOM, fetch(), localStorage. Thin; decisions belong in core.',
};

export const LARGE_FILE_LINES = 300;

export function generateInventory(root) {
  const modules = listFiles('src', '.js', root).map(path => readModule(path, root));
  const declarations = modules.flatMap(m => m.declarations);
  const lines = [
    '# Inventory: every module and what it declares',
    '',
    'GENERATED by `tools/maps/inventory.mjs`. Do not edit. `npm test` fails when this file no longer matches the',
    'code; run `npm run update-maps`, read what moved, and commit the map with the change.',
    '',
    modules.length + ' modules, ' + declarations.length + ' top-level declarations (' + declarations.filter(d => d.exported).length
      + ' exported). Look here BEFORE adding a function or a constant: if the concept exists, it is below.',
    '',
    'Read from the syntax tree: names declared inside a function are not listed, and the one-line summary is the',
    'first sentence of the doc comment right above the declaration ("no doc" when there is none).',
  ];

  const folders = [...new Set(modules.map(m => m.path.slice(0, m.path.lastIndexOf('/'))))].sort();
  for (const folder of folders) {
    lines.push('', '## `' + folder + '`', '', LAYERS[folder] || '(no description: add one to inventory.mjs)');
    for (const module of modules.filter(m => m.path.slice(0, m.path.lastIndexOf('/')) === folder)) {
      lines.push('', '### `' + module.path + '` (' + lineCount(module.text) + ' lines)', '', module.header || '(no header comment)', '');
      for (const decl of module.declarations) {
        lines.push('- `' + decl.name + '` ' + decl.kind + (decl.exported ? ', exported' : ', private') + ': ' + (decl.doc || 'no doc'));
      }
    }
  }

  const large = modules.map(m => [m.path, lineCount(m.text)]).filter(([, n]) => n >= LARGE_FILE_LINES);
  lines.push('', '## Files of ' + LARGE_FILE_LINES + ' lines and more', '');
  if (large.length) for (const [path, n] of large) lines.push('- `' + path + '`: ' + n + ' lines');
  else lines.push('None.');
  return lines.join('\n') + '\n';
}

/** Lines in a file as an editor numbers them: a final newline does not start another line. */
export function lineCount(text) {
  return text.split('\n').length - (text.endsWith('\n') ? 1 : 0);
}
