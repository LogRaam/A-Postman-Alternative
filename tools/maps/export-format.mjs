// Export format: CONTRACT. Every field of the history export file, read from EXPORT_FIELDS, the same list the
// importer validates with. A user's exported file must keep importing after an upgrade, so a field that SHIPPED
// may not disappear or narrow its type. The guard compares with docs/maps/export-format-released.md, the format
// as last RELEASED, never with the committed map: a plain regeneration must not absorb the removal it exists to refuse.

import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { readText } from '../source.mjs';

export const RELEASED_FILE = 'docs/maps/export-format-released.md';

async function loadFormat(root) {
  // Run, not parsed: the fields are data, and running the module reads exactly what the importer uses.
  const url = pathToFileURL(join(root, 'src/core/export-format.js')).href;
  return import(url);
}

export async function generateExportFormat(root) {
  const { EXPORT_FORMAT, EXPORT_VERSION, EXPORT_FIELDS } = await loadFormat(root);
  const released = readReleased(root);
  return [
    '# Export format: what a history export file holds',
    '',
    'GENERATED by `tools/maps/export-format.mjs` from `EXPORT_FIELDS` in `src/core/export-format.js`. Do not edit.',
    '',
    '**Contract.** Users keep these files and import them into later versions. Fields are additive only once',
    'released: removing a released field, or narrowing its type, is refused by `tests/maps.test.mjs` even in update',
    'mode, until it is declared on purpose with `ALLOW_FORMAT_FIELD_REMOVAL=1` and explained in the commit.',
    '',
    '- `format`: `' + EXPORT_FORMAT + '`',
    '- Version written: ' + EXPORT_VERSION,
    '- Last released snapshot: ' + (released.version ? released.version + ' (' + released.fields.length + ' fields)' : 'none yet, so nothing is protected'),
    '',
    '| Field | Type |',
    '|---|---|',
    ...EXPORT_FIELDS.map(([path, type]) => '| `' + path + '` | ' + type.split('|').join(' or ') + ' |'),
  ].join('\n') + '\n';
}

/** The released snapshot: { version, fields: [[path, type]] }, or no version when nothing was released. */
export function readReleased(root) {
  if (!existsSync(join(root, RELEASED_FILE))) return { version: null, fields: [] };
  const text = readText(RELEASED_FILE, root);
  const version = (text.match(/^Released in: (\S+)/m) || [])[1] || null;
  const fields = [...text.matchAll(/^- `([^`]+)`: (\S+)$/gm)].map(m => [m[1], m[2]]);
  return { version, fields };
}

/** Released fields that are gone, or whose type no longer accepts everything it accepted when released. */
export async function brokenReleasedFields(root) {
  const { EXPORT_FIELDS } = await loadFormat(root);
  const now = new Map(EXPORT_FIELDS);
  return readReleased(root).fields.filter(([path, type]) => {
    if (!now.has(path)) return true;
    const accepted = now.get(path).split('|');
    return type.split('|').some(t => !accepted.includes(t));
  });
}

/** The text of the released snapshot for this version: written only by `npm run update-maps -- --record-released`. */
export async function releasedSnapshot(root, version) {
  const { EXPORT_FIELDS } = await loadFormat(root);
  return [
    '# Export format as last released',
    '',
    'Written by `npm run update-maps -- --record-released` at a release, and by nothing else. The format guard',
    'protects exactly these fields. Do not edit by hand.',
    '',
    'Released in: ' + version,
    '',
    ...EXPORT_FIELDS.map(([path, type]) => '- `' + path + '`: ' + type),
  ].join('\n') + '\n';
}
