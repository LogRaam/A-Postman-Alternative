// Dependencies: which module imports which. Cycles first, then the layer rule, then usage counts, then every edge.
// A NEW LINE here means a module has started to know about another one.

import { listFiles, readModule } from '../source.mjs';

/** Every import edge [from, to, names], sorted. */
export function importEdges(root) {
  return listFiles('src', '.js', root)
    .map(path => readModule(path, root))
    .flatMap(m => m.imports.map(imp => [m.path, imp.from, [...imp.names].sort()]))
    .sort((a, b) => (a[0] + a[1]).localeCompare(b[0] + b[1]));
}

/** Groups of modules that reach each other (strongly connected, size 2 and more), each sorted. */
export function cycles(edges) {
  const graph = new Map();
  for (const [from, to] of edges) {
    if (!graph.has(from)) graph.set(from, []);
    if (!graph.has(to)) graph.set(to, []);
    graph.get(from).push(to);
  }
  let index = 0;
  const stack = [];
  const info = new Map();
  const groups = [];
  const connect = node => {
    info.set(node, { index, low: index, onStack: true });
    index++;
    stack.push(node);
    for (const next of graph.get(node)) {
      if (!info.has(next)) { connect(next); info.get(node).low = Math.min(info.get(node).low, info.get(next).low); }
      else if (info.get(next).onStack) info.get(node).low = Math.min(info.get(node).low, info.get(next).index);
    }
    if (info.get(node).low === info.get(node).index) {
      const group = [];
      let member;
      do { member = stack.pop(); info.get(member).onStack = false; group.push(member); } while (member !== node);
      if (group.length > 1) groups.push(group.sort());
    }
  };
  for (const node of [...graph.keys()].sort()) if (!info.has(node)) connect(node);
  return groups.sort((a, b) => a[0].localeCompare(b[0]));
}

/** Edges that break the layer rule: core must never import ui. */
export function layerViolations(edges) {
  return edges.filter(([from, to]) => from.startsWith('src/core/') && !to.startsWith('src/core/'));
}

export function generateDependencies(root) {
  const edges = importEdges(root);
  const groups = cycles(edges);
  const violations = layerViolations(edges);
  const lines = [
    '# Dependencies: which module imports which',
    '',
    'GENERATED by `tools/maps/dependencies.mjs`. Do not edit. `npm test` fails when this file no longer matches the',
    'code; run `npm run update-maps`, read what moved, and commit the map with the change.',
    '',
    'Read from static `import { ... } from` declarations, which are the only form the build accepts. A module that',
    'reached another through a global would not show here; the build joins every module into one scope, so',
    'nothing stops that but review.',
    '',
    '## Cycles',
    '',
    'Modules that reach each other. Inside a cycle nothing can be understood or tested alone, and the build',
    'refuses one anyway. Ratchet: may not grow (`tools/maps/ratchets.mjs`, checked by `tests/maps.test.mjs`).',
    '',
  ];
  if (groups.length) groups.forEach((g, i) => lines.push('- Group ' + (i + 1) + ': ' + g.map(p => '`' + p + '`').join(', ')));
  else lines.push('None.');

  lines.push('', '## Layer rule: core never imports ui', '', 'Ratchet: may not grow (`tools/maps/ratchets.mjs`, checked by `tests/maps.test.mjs`).', '');
  if (violations.length) for (const [from, to] of violations) lines.push('- `' + from + '` imports `' + to + '`');
  else lines.push('None.');

  const count = (index) => {
    const counts = new Map();
    for (const edge of edges) counts.set(edge[index], (counts.get(edge[index]) || 0) + 1);
    return [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  };
  lines.push('', '## Imported by the most modules', '');
  for (const [path, n] of count(1)) lines.push('- `' + path + '`: ' + n);
  lines.push('', '## Importing the most modules', '');
  for (const [path, n] of count(0)) lines.push('- `' + path + '`: ' + n);

  lines.push('', '## Every edge', '', '| Module | Imports | Names |', '|---|---|---|');
  for (const [from, to, names] of edges) lines.push('| `' + from + '` | `' + to + '` | ' + names.map(n => '`' + n + '`').join(', ') + ' |');
  return lines.join('\n') + '\n';
}
