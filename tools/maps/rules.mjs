// Rules: every test name, grouped by file and describe block. The closest thing to a specification: a behaviour
// that matters is held by a test, so a behaviour that changed shows here as a test that was renamed, added or removed.

import { listFiles, readModule } from '../source.mjs';

export function generateRules(root) {
  const files = listFiles('tests', '.test.mjs', root).map(path => readModule(path, root));
  let total = 0;
  const body = [];
  for (const file of files) {
    const groups = [];
    collect(file.ast, [], groups);
    total += groups.reduce((n, g) => n + g.tests.length, 0);
    body.push('', '## `' + file.path + '`', '', file.header || '(no header comment: say why this file exists)');
    for (const group of groups) {
      body.push('', group.path.length ? '### ' + group.path.join(' / ') : '### (top level)', '');
      for (const name of group.tests) body.push('- ' + name);
    }
  }
  return [
    '# Rules: what the tests promise',
    '',
    'GENERATED by `tools/maps/rules.mjs`. Do not edit. `npm test` fails when this file no longer matches the',
    'code; run `npm run update-maps`, read what moved, and commit the map with the change.',
    '',
    total + ' tests in ' + files.length + ' files. Read from `describe(...)` and `test(...)` calls whose name is a',
    'plain string; a test named by a variable or a template is not listed.',
    ...body,
  ].join('\n') + '\n';
}

function collect(node, path, groups) {
  if (!node || typeof node.type !== 'string') return;
  if (node.type === 'CallExpression' && node.callee.type === 'Identifier' && ['describe', 'test', 'it'].includes(node.callee.name)) {
    const first = node.arguments[0];
    const name = first && first.type === 'Literal' && typeof first.value === 'string' ? first.value : null;
    if (name && node.callee.name === 'describe') {
      const inner = [...path, name];
      for (const arg of node.arguments.slice(1)) collect(arg, inner, groups);
      return;
    }
    if (name) {
      let group = groups.find(g => g.path.join('\u0000') === path.join('\u0000'));
      if (!group) { group = { path, tests: [] }; groups.push(group); }
      group.tests.push(name);
      return;
    }
  }
  for (const key of Object.keys(node)) {
    const value = node[key];
    if (Array.isArray(value)) value.forEach(child => collect(child, path, groups));
    else if (value && typeof value.type === 'string') collect(value, path, groups);
  }
}
